import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { run, isWin } from './run.mjs';

/** Source of the launcher that starts the gateway with the secrets from <dataDir>/.env. */
export function launcherSource({ entry, port }) {
  return `// Generated by claude-omniroute-kit. Starts the OmniRoute gateway with the secrets in the .env next to this file.
import { spawn } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const env = { ...process.env };
for (const line of fs.readFileSync(path.join(here, '.env'), 'utf8').split(/\\r?\\n/)) {
  const m = line.match(/^\\s*([A-Za-z_][A-Za-z0-9_]*)\\s*=\\s*(.*?)\\s*$/);
  if (m && !line.trim().startsWith('#')) env[m[1]] = m[2];
}
const ENTRY = ${JSON.stringify(entry)};
const args = ['serve', '--daemon', '--no-open', '--no-tray', '--port', String(env.PORT || ${port})];
const child = ENTRY
  ? spawn(process.execPath, [ENTRY, ...args], { env, detached: true, stdio: 'ignore', windowsHide: true })
  : spawn('omniroute', args, { env, detached: true, stdio: 'ignore', windowsHide: true, shell: true });
child.unref();
`;
}

export async function enableAutostart({ launcher }) {
  const node = process.execPath;
  if (isWin) {
    const dir = path.join(process.env.APPDATA ?? path.join(os.homedir(), 'AppData', 'Roaming'), 'Microsoft', 'Windows', 'Start Menu', 'Programs', 'Startup');
    const file = path.join(dir, 'OmniRoute Gateway.vbs');
    const q = (s) => `""${s}""`;
    fs.mkdirSync(dir, { recursive: true });
    fs.writeFileSync(file, `CreateObject("WScript.Shell").Run "${q(node)} ${q(launcher)}", 0, False\r\n`);
    return { ok: true, where: file };
  }
  if (process.platform === 'darwin') {
    const file = path.join(os.homedir(), 'Library', 'LaunchAgents', 'dev.omniroute.gateway.plist');
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(
      file,
      `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
<key>Label</key><string>dev.omniroute.gateway</string>
<key>ProgramArguments</key><array><string>${node}</string><string>${launcher}</string></array>
<key>RunAtLoad</key><true/>
</dict></plist>
`,
    );
    await run('launchctl', ['load', '-w', file]);
    return { ok: true, where: file };
  }
  const file = path.join(os.homedir(), '.config', 'systemd', 'user', 'omniroute-gateway.service');
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(
    file,
    `[Unit]
Description=OmniRoute gateway (claude-omniroute-kit)

[Service]
Type=oneshot
RemainAfterExit=yes
ExecStart=${node} ${launcher}

[Install]
WantedBy=default.target
`,
  );
  await run('systemctl', ['--user', 'daemon-reload']);
  const r = await run('systemctl', ['--user', 'enable', 'omniroute-gateway.service']);
  return { ok: r.code === 0, where: file };
}
